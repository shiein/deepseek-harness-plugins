/** 可信 DSH 用户确认到执行指纹批准（方案 §8、§13）；不向 Agent 开放 approve 参数，不在无确认时产生授权。 */
import type { ApprovalService } from '@deepseek-ai/dsh-user-approval'
import type { ToolRunContext } from '@deepseek-ai/dsh-tools'
import {
  collectExecutionItems, executionComponentHashes, executionFingerprint,
} from '../shared/config/fingerprint.ts'
import { loadWorkspaceProjects } from '../shared/config/projects.ts'
import type { EffectiveProjectConfig } from '../shared/config/loader.ts'
import { resolveProjectPath } from '../shared/config/paths.ts'
import { fingerprintJson } from '../shared/fingerprint.ts'
import type { PreviewCaller } from './caller.ts'

/**
 * `allowed-once` 的结果不落盘——批准指纹只交还调用方（Host 内存），由 SessionRegistry 维持
 * 会话级授权（同会话、同执行指纹持续有效，2026-11-03 Aesc 决策）并随 start IPC 传给 Runner。
 * `hashes` 供下一次询问时做人读差异对照。
 */
export type ExecutionApprovalResult =
  | { outcome: 'approved'; fingerprint: string; hashes: Record<string, string> }
  // policy: 'never' 表示会话审批策略（如 Full access 预设）在任何人看到之前就确定性拒绝了本次请求。
  | { outcome: 'rejected' | 'cancelled' | 'unavailable' | 'changed'; policy?: 'never' }

type ApprovalSeam = Pick<ApprovalService, 'request'> & Partial<Pick<ApprovalService, 'overrideOf' | 'config'>>

/** 会话的生效策略：会话覆盖值，否则部署默认（官方服务语义）；读不到时不臆测。 */
function effectivePolicy(service: ApprovalSeam, exec: ToolRunContext): string | undefined {
  try {
    const session = exec.agent?.session
    return (session === undefined ? undefined : service.overrideOf?.(session)) ?? service.config?.policy
  } catch { return undefined }
}
export class ExecutionApprovalError extends Error {
  constructor(cause?: unknown) {
    super('Official DSH user approval and its audit could not be confirmed', { cause })
    this.name = 'ExecutionApprovalError'
  }
}

/**
 * 只由 Host 持有的官方 service 回答；不存在/无 Agent/拒绝/取消均不产生批准。
 * previous 是同 owner 存活授权的组件哈希（内存中的上一次批准）；不存在时如实显示「首次批准」。
 */
export async function requestExecutionApproval(
  service: ApprovalSeam | undefined,
  dataDir: string,
  caller: PreviewCaller,
  config: EffectiveProjectConfig,
  exec: ToolRunContext,
  previous?: Record<string, string>,
  /** 插件从入口自动生成的 setup（计划 generatedSetup）；并入指纹并在弹窗中列出。 */
  generated?: { entry: string, hash: string },
): Promise<ExecutionApprovalResult> {
  if (!service || !exec.agent || exec.agent.session.id !== caller.ownerSessionId) return { outcome: 'unavailable' }
  if (exec.signal.aborted) return { outcome: 'cancelled' }
  const appRoot = await resolveProjectPath(caller.workspaceRoot, config.project.root)
  const items = await collectExecutionItems(appRoot, config.project)
  const fingerprint = executionFingerprint(items, generated?.hash)
  // 是否需要询问由 SessionRegistry 的会话级授权决定；进入这里就一定询问，不在此复用旧答复。
  const hashes = executionComponentHashes(items, generated?.hash)
  const changed = [...new Set([...Object.keys(previous ?? {}), ...Object.keys(hashes)])]
    .filter(name => previous?.[name] !== hashes[name])
  // 人读差异：哪条命令/哪个文件/哪个环境变量变了；哈希只进 Details 段供核对（方案 §13.1）。
  const describe = (name: string): string => {
    let state = 'changed'
    if (previous === undefined) state = 'new'
    else if (previous[name] === undefined) state = 'added'
    else if (hashes[name] === undefined) state = 'removed'
    if (name === 'application-root') return 'application root binding ' + state
    if (name === 'command') return 'command ' + state + (
      state === 'removed' ? ' (no command is bound now)' : ' (current command is shown above)')
    if (name === 'setup') return 'setup file ' + (items.bindings.setup?.path ?? 'binding') + ' ' + state
    if (name === 'environment-binding') return 'environment variable set ' + state
    if (name === 'generated-setup') {
      return 'setup generated by the plugin from ' + (generated?.entry ?? 'the entry') + ' ' + state
    }
    if (name.startsWith('build-config:')) {
      return 'build configuration ' + name.slice('build-config:'.length) + ' ' + state
    }
    if (name.startsWith('environment:')) return 'environment variable ' + name.slice('environment:'.length) + (
      ' ' + state + ' (value is never shown)')
    if (name.startsWith('handler:')) {
      const hname = name.slice('handler:'.length)
      const hpath = items.bindings.handlers[hname]?.path ?? 'binding removed'
      return 'handler for scenario ' + hname + ' (' + hpath + ') ' + state
    }
    return name + ' ' + state
  }
  const changes = previous === undefined
    ? 'First approval for this project: every execution item above is new; there is no earlier grant to compare.'
    : changed.length ? changed.map(name => '- ' + describe(name)).join('\n')
      : '- none (the execution items are identical; a fresh confirmation is still required for every run)'
  const details = changed.map(name =>
      '- ' + name + ': ' + (previous?.[name]?.slice(0, 12) ?? 'not approved')
      + ' -> ' + (hashes[name]?.slice(0, 12) ?? 'removed')
    ).join('\n') || '- none'
  const command = items.command
    ? JSON.stringify({ executable: items.command.executable, args: items.command.args, cwd: items.bindings.cwd })
    : 'none'
  const modules = [items.bindings.setup?.resolved,
    ...Object.values(items.bindings.handlers).map(value => value.resolved),
  ].filter(value => value !== undefined)
  const description = 'Project: ' + config.project.id + '\nWorkspace: ' + caller.workspaceRoot
    + '\nApplication: ' + appRoot
    + '\nConfiguration: ' + (config.source.kind === 'detected' ? 'detected metadata' : config.source.file)
    + '\nCommand: ' + command + '\nEnvironment names only: ' + Object.keys(items.env ?? {}).join(', ')
    + '\nSetup/handlers: ' + modules.join(', ')
    + '\nBuild configuration (runs as Node code): ' + (items.bindings.buildConfig?.join(', ') ?? 'none')
    + (generated ? '\nGenerated setup: replays the registrations of ' + generated.entry
      + ' (business router replaced by an inert router; login/API calls not executed)' : '')
    + '\nChanges since the last approval:\n' + changes
    + '\nDetails (component hashes):\n' + details + '\nFingerprint: ' + fingerprint
  let outcome: Awaited<ReturnType<ApprovalService['request']>>
  try { outcome = await service.request({
    agent: exec.agent, toolName: exec.name, callId: exec.callId, signal: exec.signal,
    reason: 'Allow this preview execution for project ' + config.project.id + ': ' + fingerprint,
    // displayReason 仅给用户界面，不持久化进 SDK 审计；命令参数不进入 reason/模型输出。
    // 文案必须如实说明有效范围：官方按钮叫「允许一次」，但插件把它用作本会话内对这组执行项的批准；
    // 执行项变化、换会话或 DSH 重启都会再次询问。
    // 官方 locale 回退链只查 "zh"/"en" 键（dsh-client-locale resolveText），zh-CN 永不命中。
    displayReason: {
      en: 'Approve running these execution items for this workspace/project?'
        + ' The approval stays valid in this DSH session while these execution items are unchanged;'
        + ' any change, another session or a DSH restart asks again.'
        + ' Project code runs with local user permissions.\n' + description,
      zh: '是否批准运行本工作区/项目的以下执行项？批准在本 DSH 会话内、且这些执行项不变时持续有效；'
        + '执行项变化、换会话或 DSH 重启都会再次询问。项目代码以本机用户权限运行。\n' + description,
    },
  }) } catch (error) { throw new ExecutionApprovalError(error) }
  if (outcome !== 'allowed-once') {
    const byPolicy = outcome === 'rejected' && effectivePolicy(service, exec) === 'never'
    return byPolicy ? { outcome, policy: 'never' } : { outcome }
  }
  if (exec.signal.aborted) return { outcome: 'cancelled' }
  const explicit = config.source.kind === 'explicit' ? config.source.file : undefined
  const fresh = (await loadWorkspaceProjects(caller.workspaceRoot, explicit, { dataDir })).find(value => value.config.project.id === config.project.id)
  if (!fresh || fingerprintJson(fresh.config.project) !== fingerprintJson(config.project)) return { outcome: 'changed' }
  const refreshed = await collectExecutionItems(await resolveProjectPath(caller.workspaceRoot, fresh.config.project.root), fresh.config.project)
  if (executionFingerprint(refreshed, generated?.hash) !== fingerprint) return { outcome: 'changed' }
  if (exec.signal.aborted) return { outcome: 'cancelled' }
  return { outcome: 'approved', fingerprint, hashes: executionComponentHashes(refreshed, generated?.hash) }
}
