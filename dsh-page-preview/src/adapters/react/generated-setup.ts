/**
 * 插件自动生成并使用的 React setup（方案 §0.3 第 10 条、§6.9；R5-7）。项目未配置 runtime.setup 时，从
 * 应用入口重放 Provider 链（第三方与业务祖先 JSX 元素按原顺序）、样式与副作用导入；路由元素在运行时
 * 换成 MemoryRouter 内存上下文。预检只读生成并取摘要计入执行指纹；worker 启动前用同一函数重新生成并
 * 核对摘要，入口在批准后被改动则拒绝执行。生成源码只在 Runner 内作为模块加载，不写入目标项目，
 * 也不进工具输出。模块是普通 JS（createElement），不要求项目配置 JSX 运行时之外的转换。
 */
import { createHash } from 'node:crypto'
import { relative } from 'node:path'
import { parseEntryRegistrations } from './entry-replay.ts'
import type { EntryReplayResult } from './entry-replay.ts'
import type { ReactMajor } from './detect.ts'

export interface GeneratedSetup {
  /** 入口相对应用根。 */
  entry: string
  source: string
  hash: string
  replay: EntryReplayResult
}

interface EmitOptions { importPath?: (file: string) => string }

/** 生成模块源码：第三方与业务 Provider 重放，叶组件留空由预览目标挂载。 */
export function generateSetupDraft(replay: EntryReplayResult, options: EmitOptions = {}): string {
  const draft = replay.draft
  const importPath = options.importPath ?? ((file: string) => file)
  const needed = new Set<string>()
  for (const layer of draft.layers) {
    if (layer.kind === 'provider' || layer.kind === 'router') for (const name of layer.imports) needed.add(name)
  }
  // 路由层标签（BrowserRouter 等）不引入原符号——统一替换为 MemoryRouter。
  for (const layer of draft.layers) if (layer.kind === 'router') needed.delete(layer.name)
  const lines: string[] = ['// Generated by dsh-page-preview from the application entry; do not edit.']
  lines.push("import { createElement as __e } from 'react'")
  if (draft.layers.some(layer => layer.kind === 'strict'))
    lines.push("import { StrictMode as __StrictMode } from 'react'")
  if (draft.layers.some(layer => layer.kind === 'router'))
    lines.push("import { MemoryRouter as __MemoryRouter } from 'react-router-dom'")
  for (const item of draft.imports) {
    const bindings = item.bindings.filter(binding => needed.has(binding.local))
    if (!bindings.length) continue
    const parts: string[] = []
    const defaults = bindings.filter(binding => binding.imported === 'default')
    const stars = bindings.filter(binding => binding.imported === '*')
    const named = bindings.filter(binding => binding.imported !== 'default' && binding.imported !== '*')
    for (const star of stars) parts.push('* as ' + star.local)
    for (const binding of defaults) parts.push(binding.local)
    if (named.length) parts.push('{ ' + named.map(binding => binding.imported === binding.local
      ? binding.local : binding.imported + ' as ' + binding.local).join(', ') + ' }')
    const specifier = item.resolvedSource !== item.source && item.resolvedSource.startsWith('/')
      ? importPath(item.resolvedSource) : item.source
    lines.push('import ' + parts.join(', ') + ' from ' + JSON.stringify(specifier))
  }
  for (const item of draft.imports) {
    if (item.bindings.length || item.excluded) continue
    const specifier = item.resolvedSource.startsWith('/') ? importPath(item.resolvedSource) : item.source
    lines.push('import ' + JSON.stringify(specifier))
  }
  const emittedDeclarations = new Set<string>()
  for (const layer of draft.layers) {
    if (layer.kind !== 'provider') continue
    for (const name of layer.declarations) {
      if (emittedDeclarations.has(name)) continue
      const declaration = draft.declarations.find(value => value.name === name)
      if (declaration) { emittedDeclarations.add(name); lines.push(declaration.source) }
    }
  }
  lines.push('var __pending = [' + JSON.stringify('/') + ']')
  const layerExpr = (layer: EntryReplayResult['draft']['layers'][number], inner: string): string => {
    if (layer.kind === 'strict') return '__e(__StrictMode, null, ' + inner + ')'
    if (layer.kind === 'router') return '__e(__MemoryRouter, { initialEntries: __pending }, ' + inner + ')'
    const props = layer.props.length
      ? '{ ' + layer.props.map(prop => JSON.stringify(prop.name) + ': ' + prop.text).join(', ') + ' }'
      : 'null'
    return '__e(' + layer.name + ', ' + props + ', ' + inner + ')'
  }
  const layers = [...draft.layers].reverse()
  lines.push('export default {')
  lines.push('  createContext: function () {')
  lines.push('    return {')
  lines.push('      wrap: function (child) {')
  lines.push('        var el = child')
  for (const layer of layers) lines.push('        el = ' + layerExpr(layer, 'el'))
  lines.push('        return el')
  lines.push('      },')
  lines.push('      __pending: __pending,')
  lines.push('    }')
  lines.push('  },')
  lines.push('  navigate: function (input) {')
  lines.push('    input.context.__pending[0] = input.href')
  lines.push('    return input.href')
  lines.push('  },')
  lines.push('  dispose: function () {},')
  lines.push('}')
  return lines.join('\n') + '\n'
}

/**
 * importPath：绝对文件路径在生成模块中的导入写法（Vite 用裸绝对路径交其解析，webpack 原样）。
 * 无法重放（语法无效、无 createRoot().render(JSX)、叶不明）时返回原因，由调用方走手写 setup 路径。
 */
export async function buildGeneratedSetup(
  appRoot: string, entry: string, major: ReactMajor | 'unknown', importPath?: (file: string) => string,
): Promise<GeneratedSetup | { reason: string, replay?: EntryReplayResult }> {
  const replay = await parseEntryRegistrations(appRoot, entry)
  if (replay.invalid) return { reason: 'Entry syntax is invalid', replay }
  if (major === 'unknown') return { reason: 'Installed React major version is unknown', replay }
  if (!replay.draft.leaf) return { reason: 'The entry has no replayable React render tree', replay }
  if (replay.draft.layers.some(layer => layer.kind === 'provider' && layer.origin === 'unresolved')) {
    return { reason: 'The entry provider chain cannot be fully resolved', replay }
  }
  const source = generateSetupDraft(replay, importPath ? { importPath } : {})
  const hash = createHash('sha256').update(source).digest('hex')
  return { entry: relative(appRoot, replay.entryFile), source, hash, replay }
}

/** worker 启动前：按计划记录的入口重新生成，并与批准时的摘要一致才可加载。 */
export async function verifiedGeneratedSetup(
  appRoot: string, planned: { entry: string, hash: string }, reactVersion: string | undefined,
  importPath?: (file: string) => string,
): Promise<string> {
  const major: ReactMajor | 'unknown' = reactVersion?.startsWith('18.') ? '18'
    : reactVersion?.startsWith('19.') ? '19' : 'unknown'
  const built = await buildGeneratedSetup(appRoot, planned.entry, major, importPath)
  if ('reason' in built) throw new Error('The generated setup can no longer be built: ' + built.reason)
  if (built.hash !== planned.hash) {
    throw new Error('The application entry changed after the generated setup was approved; open the preview again')
  }
  return built.source
}

/** 计划 knownDifferences 用的人读摘要：只含数量、标签名、行号与模块说明符，不含原始表达式。 */
export function generatedSetupNotes(built: GeneratedSetup): string[] {
  const providers = built.replay.draft.layers.filter(layer => layer.kind === 'provider')
  const router = built.replay.draft.layers.some(layer => layer.kind === 'router')
  return [
    'Initialization is replayed from ' + built.entry + ' through a plugin-generated setup (' + providers.length
      + ' provider layers' + (router ? ', router context via in-memory MemoryRouter' : '')
      + '); the business leaf component is replaced by the preview target and entry login/API calls are not executed',
    ...built.replay.diagnostics.map(value => 'Not replayed: ' + value),
  ]
}


